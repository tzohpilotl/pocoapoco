import "dotenv/config";
import { join } from "node:path";
import { DataSource } from "typeorm";
import { Project } from "./entities/project.entity";
import { ProjectStatus } from "./entities/project-status.entity";
import { ProjectStatusConfiguration } from "./entities/project-status-configuration.entity";
import { ProjectStatusLog } from "./entities/project-status-log.entity";
import { User } from "./entities/user.entity";

export const AppDataSource = new DataSource({
  type: "postgres",
  host: process.env.DB_HOST ?? "localhost",
  port: Number(process.env.DB_PORT ?? 5432),
  username: process.env.DB_USER ?? "tracking_service",
  password: process.env.DB_PASSWORD ?? "tracking_service",
  database: process.env.DB_NAME ?? "tracking_service",
  entities: [User, Project, ProjectStatus, ProjectStatusLog, ProjectStatusConfiguration],
  // __dirname resolves to src/ under ts-node (local dev/migration:generate) and
  // to dist/ once compiled (production) — this glob matches migrations
  // generated by either, so the same file works in both contexts without a
  // separate prod-only datasource.
  migrations: [join(__dirname, "migrations", "*.{ts,js}")],
  synchronize: false,
});
